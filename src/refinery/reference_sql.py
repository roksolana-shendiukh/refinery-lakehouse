"""Renders a reference CSV as a SQL view with the rows inlined (SELECT ... FROM VALUES).

Used for the live pipeline, which must not depend on the batch pipelines: the CSV in
data/reference stays the single source, and the generated SQL file is a build output of it.
"""

import csv
from dataclasses import dataclass
from pathlib import Path

GENERATED_HEADER = "-- Generated by scripts/generate_live_reference.py from {source}. Do not edit by hand."


@dataclass(frozen=True)
class ReferenceView:
    view_name: str
    comment: str
    source_csv: str
    column_types: dict[str, str]


def sql_string(value: str) -> str:
    """A SQL string literal; single quotes are doubled, backslashes escaped."""
    return "'" + value.replace("\\", "\\\\").replace("'", "''") + "'"


def read_rows(path: Path, columns: list[str]) -> list[list[str]]:
    with path.open(newline="", encoding="utf-8") as file:
        reader = csv.DictReader(file)
        if reader.fieldnames != columns:
            raise ValueError(f"{path}: expected columns {columns}, found {reader.fieldnames}")
        return [[row[column] for column in columns] for row in reader]


def render_view(view: ReferenceView, rows: list[list[str]]) -> str:
    columns = list(view.column_types)
    select_list = ",\n  ".join(
        name if sql_type == "STRING" else f"CAST({name} AS {sql_type}) AS {name}"
        for name, sql_type in view.column_types.items()
    )
    values = ",\n  ".join("(" + ", ".join(sql_string(value) for value in row) + ")" for row in rows)
    alias = Path(view.source_csv).stem
    return (
        f"{GENERATED_HEADER.format(source=view.source_csv)}\n\n"
        f"CREATE VIEW {view.view_name}\n"
        f"COMMENT {sql_string(view.comment)}\n"
        f"AS\n"
        f"SELECT\n  {select_list}\n"
        f"FROM VALUES\n  {values}\n"
        f"AS {alias}({', '.join(columns)});\n"
    )


def render_from_csv(view: ReferenceView, repo_root: Path) -> str:
    rows = read_rows(repo_root / view.source_csv, list(view.column_types))
    return render_view(view, rows)
