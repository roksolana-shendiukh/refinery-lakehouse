import re

import pytest

from refinery.reference_sql import ReferenceView, read_rows, render_view, sql_string

VIEW = ReferenceView(
    view_name="live_ref_example",
    comment="Example's comment",
    source_csv="data/reference/ref_example.csv",
    column_types={"code": "SMALLINT", "name": "STRING"},
)


def _query(sql: str) -> str:
    """The SELECT part of a generated view, runnable on local Spark."""
    return re.search(r"\nAS\n(SELECT.*);", sql, re.DOTALL).group(1)


def test_sql_string_doubles_single_quotes():
    assert sql_string("People's Republic") == "'People''s Republic'"


def test_sql_string_escapes_backslashes():
    assert sql_string("a\\b") == "'a\\\\b'"


def test_render_view_casts_typed_columns_and_keeps_strings(spark):
    sql = render_view(VIEW, [["405", "Bangladesh (People's Republic of)"], ["201", "Albania"]])

    rows = spark.sql(_query(sql)).collect()

    assert [(row.code, row.name) for row in rows] == [(405, "Bangladesh (People's Republic of)"), (201, "Albania")]
    assert dict(spark.sql(_query(sql)).dtypes) == {"code": "smallint", "name": "string"}


def test_render_view_names_the_view_and_its_source():
    sql = render_view(VIEW, [["1", "x"]])

    assert sql.startswith("-- Generated by scripts/generate_live_reference.py from data/reference/ref_example.csv.")
    assert "CREATE VIEW live_ref_example\nCOMMENT 'Example''s comment'" in sql


def test_read_rows_rejects_unexpected_columns(tmp_path):
    path = tmp_path / "ref.csv"
    path.write_text("code,label\n1,x\n", encoding="utf-8")

    with pytest.raises(ValueError, match="expected columns"):
        read_rows(path, ["code", "name"])
